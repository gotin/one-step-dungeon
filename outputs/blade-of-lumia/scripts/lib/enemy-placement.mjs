export function tilesOf(stage) {
	return (stage.tiles ?? []).map(row => (Array.isArray(row) ? row.slice() : String(row).split('')));
}

// 部屋の脅威度＝雑魚（ボス除く）の hp*atk/(def+1) の合計。
export function stageThreat(stage, ENEMY_META) {
	let t = 0;
	for (const row of tilesOf(stage)) {
		for (const ch of row) {
			const meta = ENEMY_META[ch];
			if (meta && !meta.isBoss) t += THREAT_OF(meta);
		}
	}
	return t;
}
