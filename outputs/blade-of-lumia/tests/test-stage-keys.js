/**
 * 検証ステージ名 → ステージキー。未知の名前は即エラー（typo で別ステージを
 * 開いてテストが無言で通る／落ちるのを防ぐ）。
 * @param {string} name
 * @returns {string}
 */
export function stageKey(name) {
	const key = TEST_STAGE_KEYS[name];
	if (!key) {
		throw new Error(
			`未知のテストステージ名: ${name}（tests/test-stage-keys.js の表に追加すること）`,
		);
	}
	return key;
}
