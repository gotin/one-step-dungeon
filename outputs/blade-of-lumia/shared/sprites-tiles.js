//   'blanket' …裾まで下りた雪（下半分まで来る＝雪山）。岩と輪郭は必ず残す
//   'none'    …雪を1ドットも置かない
//   'ember'   …雪ではなく溶岩の熾火（5 を火口と溶岩の筋に使う）
// `marks` ＝[行番号, 列0, 列1, 色]（3ドット以上のかたまり＝3.375px の粒に見えない）。
