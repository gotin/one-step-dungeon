// セル座標などから決まる整数ハッシュ。「同じ画面はいつ来ても同じ絵」にするため
// 乱数は使わない（マップデータも変えない）。地面の変種選択・橋の木目に使う。
export function tileHash(a, b) {
	let h = Math.imul((a | 0) + 0x9e37, 73856093) ^ Math.imul((b | 0) + 0x85eb, 19349663);
	h = Math.imul(h ^ (h >>> 13), 1274126177);
	return (h ^ (h >>> 16)) >>> 0;
}

