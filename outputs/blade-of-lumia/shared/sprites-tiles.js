// ── 板の「模様の周期」を殺す（方針C・2026-09-06 ユーザー承認）──────
// 断面だけのデッキは、どのセルも全く同じ絵＝12セル並べると 1296px の一枚板になり、
// 色が1ドットも変わらない＝「板状のところがのっぺりしすぎて違和感」（ユーザー指摘）。
// 本物の桟橋は板の端（木口）がレンガのように互い違い＝千鳥になっている。
// ∴ ①板ごとに木口を千鳥で入れる ②板ごとに地の色を微妙に変える＋まばらに木目を引く。
//
// ⚠ ドットのピッチ（32×32）は変えない＝ここで直すのは「周期」だけ。
// ⚠ SPRITES は import 時の spread で確定する（shared/sprites.js）∴変種は遅延生成できない。
//    ∴ 行 5 × 列 3 の周期で作り置きし、セル座標から名前を引く（connectVariantName）。
//    周期を素数どうし（5 と 3）にすると、繰り返しは 5セル×3セル＝画面より広くなる。
const BR_PLANKS_PER_CELL = BR_N / BR_PLANK;      // セル内の板の枚数（4）
// 木口の列は「隣り合う板どうしで循環距離 6 ドット以上」離す＝縦に揃わない（千鳥）。
// 0/31 を避けるのはセル境界の真上に木口が来ないようにするため。
const BR_SEAM_OFF = [3, 16, 9, 22, 28];          // 板ごとの木口の列。長さ＝行方向の変種の数
const BR_SEAM_JIT = [0, 5, 11];                  // セル列ごとのずらし。長さ＝列方向の変種の数
const BR_TONE     = [3, 7, 3, 8, 7];             // 板ごとの地の色（3 を基準に ±1段）
export const BR_VAR_ROWS = BR_SEAM_OFF.length;   // ＝BR_TONE.length（板の並びで1周する）
export const BR_VAR_COLS = BR_SEAM_JIT.length;

// 木目＝板の向きに沿った1ドットの筋。3枚に1枚だけ・長さ3〜6ドット（まばら）。
// 板の向きに沿うので柱には見えない（＝畑のうねを作らない）。
function brGrain(band, j, sub) {
	const h = tileHash(band * 2 + sub, j * 31 + 7);
	if (h % 3) return null;
	const len = 3 + (h >>> 5) % 4;
	const start = (h >>> 9) % (BR_N - len);
	return [start, start + len];
}

// デッキH＝板が東西に走る（南北に渡る橋＝進行方向と直交）。断面の周期は BR_PLANK の
// ままなので、セル境界を越えても板の高さは揃う＝1枚の長い板に見える。
function brDeckH(i, j) {
	const planks = Array.from({ length: BR_PLANKS_PER_CELL }, (_, b) => {
		const band = BR_PLANKS_PER_CELL * i + b;     // 変種の周期の中での板の通し番号
		const k    = band % BR_VAR_ROWS;
		return {
			tone:  BR_TONE[k],
			seam:  (BR_SEAM_OFF[k] + BR_SEAM_JIT[j]) % BR_N,
			grain: [brGrain(band, j, 0), brGrain(band, j, 1)],
		};
	});
	return brGrid((r, c) => {
		const p  = planks[Math.floor(r / BR_PLANK)];
		const rr = r % BR_PLANK;
		let v = BR_PLANK_ROWS[rr];
		if (v === 3) v = p.tone;                     // 板の地＝板ごとに微妙に違う
		const g = rr === 3 ? p.grain[0] : rr === 5 ? p.grain[1] : null;
		if (g && c >= g[0] && c < g[1]) v = 2;       // 木目
		if (c === p.seam) v = 6;                     // 木口（板の端）＝板を横切る2ドット
		else if (c === (p.seam + 1) % BR_N) v = 1;
		return v;
	});
}

// デッキV＝板が南北に走る（東西に渡る橋）。deckH の転置＝行と列の役割が入れ替わる∴
// 変種の引き方も (r,c) が入れ替わる（connectVariantName 側で対応）。
for (let i = 0; i < BR_VAR_ROWS; i++) {
	for (let j = 0; j < BR_VAR_COLS; j++) {
		const g = brDeckH(i, j);
		TILE_SPRITES[`bridgeDeckH@${i},${j}`] = [g];
		TILE_SPRITES[`bridgeDeckV@${i},${j}`] = [brTranspose(g)];
	}
}
// 変種を持たない呼び出し（パレット見本・世界地図のサムネイル）用の代表1枚。
TILE_SPRITES.bridgeDeckH = TILE_SPRITES['bridgeDeckH@0,0'];
TILE_SPRITES.bridgeDeckV = TILE_SPRITES['bridgeDeckV@0,0'];

// 手すり（rail）＝落ちる隣（水/溶岩）に面した辺に立てる。
// 断面＝外側の輪郭2＋笠木の明部3＋その影1（計6ドット＝画面 20px）、内側へ支柱が4ドット。
// 支柱は BR_POST 間隔・幅3∴隣セルへ繋いでも等間隔に並ぶ（セル内に2本）。
const BR_RAIL_ROWS  = [1, 1, 4, 4, 4, 2];        // 辺から内側へ向かう断面
const BR_POST_DEPTH = BR_RAIL_ROWS.length + 4;   // 支柱の先端（辺から数えたドット）
const brRailN = brGrid((r, c) => {
	if (r < BR_RAIL_ROWS.length) return BR_RAIL_ROWS[r];
	const inPost = (c % BR_POST) >= 2 && (c % BR_POST) <= 4;
	return (r < BR_POST_DEPTH && inPost) ? 2 : 0;
});
TILE_SPRITES.bridgeRailN = [brRailN];
TILE_SPRITES.bridgeRailS = [brFlipRows(brRailN)];
TILE_SPRITES.bridgeRailW = [brTranspose(brRailN)];
TILE_SPRITES.bridgeRailE = [brFlipCols(brTranspose(brRailN))];

// 木口（trim）＝陸に面した辺。手すりを立てると「渡れない縁」に見えて
// デッキへ乗り降りできる辺を塞いだように読めるので、板の端の陰だけを描く。
// ⚠ 厚みは格子の 1/16（2ドット＝画面 7px）に留める。8×8 時代の「1ドット」は
//   画面 13.5px＝これより太かった。格子の 1/4 まで太らせると陸側にも枠が回り、
//   幅2セルの渡しが「木箱」に見えた（拡大確認 2026-09-06）。
const BR_TRIM_ROWS = [1, 2];
const brTrimN = brGrid(r => BR_TRIM_ROWS[r] ?? 0);
TILE_SPRITES.bridgeTrimN = [brTrimN];
TILE_SPRITES.bridgeTrimS = [brFlipRows(brTrimN)];
TILE_SPRITES.bridgeTrimW = [brTranspose(brTrimN)];
TILE_SPRITES.bridgeTrimE = [brFlipCols(brTranspose(brTrimN))];

// 単体の `bridge` 名は残す（TILE_SPRITE_MAP・エディタのパレット見本・世界地図の
// サムネイルが参照する「そのタイルの代表1枚」）。代表＝板だけのデッキ。
TILE_SPRITES.bridge = TILE_SPRITES.bridgeDeckH;

// ── セル座標から変種を選ぶ（単一の真実）───────────────────────
// エディタ（editor/editor-canvas.js）とゲーム（game/render-board.js）の両方が
// 必ずここを通す＝「エディタとゲームで見た目が違う」を作らない。
// 決定的＝同じセルはいつ来ても同じ絵（乱数を使わない・マップデータも変えない）。

// 連結タイルの本体の変種。板の並ぶ向きが「行方向か列方向か」で
// (r,c) の役割が入れ替わる∴向きごとに引き方を持つ。
// ⚠ 周期の数（rows/cols）は本体ごとに違う（橋は 5×3・家の壁は 3×5）∴
//    引き方と一緒に持つ。ここを橋の数で固定すると、家の変種が存在しない名前
//    （`houseWallBase@4,0` など）に落ちて絵が消える。
export const CONNECT_VARIANTS = {
	bridgeDeckH: { pick: (r, c) => [r, c], rows: BR_VAR_ROWS, cols: BR_VAR_COLS },  // 板は東西＝並ぶのは行方向
	bridgeDeckV: { pick: (r, c) => [c, r], rows: BR_VAR_ROWS, cols: BR_VAR_COLS },  // 板は南北＝並ぶのは列方向
	// 家の壁・屋根はこのファイルの下（fd* ヘルパーより後）で足す。
};

// 画面外の隣（エディタの隣接プレビューは r=-0.5 のような座標で描く）でも
// 実在する名前を返す＝絵が消えない。
const varMod = (n, m) => ((Math.floor(n) % m) + m) % m;

export function connectVariantName(base, r, c) {
	const v = CONNECT_VARIANTS[base];
	if (!v) return base;
	const [a, b] = v.pick(r, c);
	return `${base}@${varMod(a, v.rows)},${varMod(b, v.cols)}`;
}

// 下地（bgTiles）に敷く地面スプライトの変種。セル座標のハッシュで選ぶ。
// 形は6種＝草地・砂地・雪原・火山灰・泥・石畳で、地形と1対1（10a-1b-4 で
// 「砂の形を灰に流用」等をやめた＝素材が違えば模様も違う）。対応は TILE_SPRITE_MAP。
// ⚠ 水（'water'）は対象外＝アニメーションする下地で、tiles 層の水・溶岩・潮ゲートと
//    同じ形を共有している。しかも 12 ドット幅は `--cell` 108px を割り切る∴既に
//    1ドット 3px で敷けている（倍率探索が s=3 を選ぶ）＝ピッチの問題が無い。
export const GROUND_VARIANTS = Object.fromEntries(
	Object.keys(GROUND_SHAPES).map(name => [name, GROUND_VARIANTS_N]));

export function bgVariantName(spr, r, c) {
	const n = GROUND_VARIANTS[spr];
	if (!n) return spr;
	return `${spr}@${tileHash(Math.floor(r), Math.floor(c)) % n}`;
}

// tiles 層に立つ物（木・山・茂み）の変種。キュー10番 10a-4。
//
// 🔴 なぜ要るか＝同じ絵が木 3173／山 2391／茂み 227 セルに並んでいた。しかも木・茂みの
//    2コマは1枚の `setInterval`（`startAnimLoop`）が全 canvas を同じコマで描き替える∴
//    林が「1本の木のコピー」に見え、さらに全画面が一斉にざわついていた。
//
// 名前の付け方（10a-1d の引き継ぎで「規則をここで決める」とした分）：
//   ・肌（下地から導く・塊単位）  … `@` ＝ `mountain@mesa`（`shared/tile-skins.js`）
//   ・変種（セル座標から引く）    … `#` ＝ `tree#3` / `mountain@mesa#2`
//   ∴ 2軸は別の記号を使う＝名前から「肌なのか変種なのか」が読める。順序は必ず
//     肌 → 変種（`objVariantName` は肌を解決した後の名前を受け取る）。
//   ⚠ パレットは変種で変えない（形と揺れの位相だけを変える）＝色の軸は肌だけが持つ。
export const OBJ_VARIANTS = {};      // 絵の名前 → 変種の数（この節の下で埋める）

export function objVariantName(base, r, c) {
	const n = OBJ_VARIANTS[base];
	if (!n) return base;
	return `${base}#${tileHash(Math.floor(r), Math.floor(c)) % n}`;
}

// ── tiles 層に置く「セルを埋めない絵」（木・山・茂み・看板）── 32×32 ────────
// キュー10番 10a-1c。それまで 8×8 で描いていて、0.7 セル（75.59px）に伸ばすと
// 1ドット＝9.45px ∴同じ画面でキャラ（3.375px）や地面（3.375px）と粗さが揃わず、
// 木や山だけ「別のゲームの絵」に見えていた。
//
// 見た目の大きさは変えない（PLAN の制約＝「セルを埋めない絵」は意図的）。
// ∴ 32×32 の格子の中に**透明の余白**を取り、絵そのものは 20〜24 ドットに収める。
// 描画側（render-board.js）はこの4種をセル全面に貼る＝1ドットが厳密に cellPx/32 に
// なり、絵の見かけの大きさは 22/32 ≒ 0.69 セルで従来と同じ。
const FIELD_ART_N = 32;
export const FIELD_N = FIELD_ART_N;

const fdBlank = () => Array.from({ length: FIELD_ART_N }, () => Array(FIELD_ART_N).fill(0));
const fdPut = (g, r, c, v) => {
	if (r >= 0 && r < FIELD_ART_N && c >= 0 && c < FIELD_ART_N) g[r][c] = v;
};
const fdSpan = (g, r, c0, c1, v) => { for (let c = c0; c <= c1; c++) fdPut(g, r, c, v); };

// 輪郭：外に接するドットを縁の色に、下端はさらに暗く＝絵が地面から浮かない。
function fdRim(g, side, bottom) {
	const src = g.map(row => [...row]);
	const empty = (r, c) => !(src[r]?.[c]);
	for (let r = 0; r < FIELD_ART_N; r++) {
		for (let c = 0; c < FIELD_ART_N; c++) {
			if (!src[r][c]) continue;
			if (empty(r + 1, c)) fdPut(g, r, c, bottom);
			else if (empty(r - 1, c) || empty(r, c - 1) || empty(r, c + 1)) fdPut(g, r, c, side);
		}
	}
}

// 絵に挟まれた1ドットの透明（上下または左右が絵）を隣の色で塞ぐ。
// 輪郭の1ドットの欠け＝3.375px の穴が地面を透かして見える（櫛の歯）。房の合併でも
// 樹冠と幹の合成でも出るので、絵を組み終えた最後に必ず通す。
function fdSeal(g) {
	const src = g.map(row => [...row]);
	for (let r = 1; r < FIELD_ART_N - 1; r++) {
		for (let c = 1; c < FIELD_ART_N - 1; c++) {
			if (src[r][c]) continue;
			if (src[r][c - 1] && src[r][c + 1]) fdPut(g, r, c, src[r][c - 1]);
			else if (src[r - 1][c] && src[r + 1][c]) fdPut(g, r, c, src[r - 1][c]);
		}
	}
	return g;
}

// 葉のかたまり（木の樹冠・茂みで共通）。房＝[行, 列, 半径, 手前の房か]。
//   ① 房（円）の合併で輪郭を作る＝でこぼこした葉の塊になる
//   ② 1ドットの欠け（円の重なりでできる隙間）を埋める＝輪郭が櫛の歯にならない
//   ③ 陰影は「塊ぜんたい」に1方向から付ける（房ごとに付けると斑になる＝試作で確認）
//   ④ 手前の房の下側の弧だけ1段暗い線＝葉のかたまりの区切りが見える
//      （全部の円のふちを引くと絵の全面が線で埋まる）
const fdDist2 = (r, c, r0, c0) => (r - r0) ** 2 + (c - c0) ** 2;
function fdFoliage(lobes, ramp) {
	const g = fdBlank();
	const inLobe = (r, c, [r0, c0, rad]) => fdDist2(r, c, r0, c0) <= rad * rad + rad * 0.5;
	const mask = [];
	let r0 = 99, r1 = -1, c0 = 99, c1 = -1;
	for (let r = 0; r < FIELD_ART_N; r++) {
		mask.push([]);
		for (let c = 0; c < FIELD_ART_N; c++) {
			const hit = lobes.some(L => inLobe(r, c, L));
			mask[r].push(hit);
			if (hit) {
				r0 = Math.min(r0, r); r1 = Math.max(r1, r);
				c0 = Math.min(c0, c); c1 = Math.max(c1, c);
			}
		}
	}
	for (let r = 0; r < FIELD_ART_N; r++) {
		for (let c = 1; c < FIELD_ART_N - 1; c++) {
			if (mask[r][c]) continue;
			if (mask[r][c - 1] && mask[r][c + 1]) mask[r][c] = true;
			else if (mask[r - 1]?.[c] && mask[r + 1]?.[c]) mask[r][c] = true;
		}
	}
	const rc = (r0 + r1) / 2, cc = (c0 + c1) / 2, R = Math.max(r1 - r0, c1 - c0) / 2;
	for (let r = 0; r < FIELD_ART_N; r++) {
		for (let c = 0; c < FIELD_ART_N; c++) {
			if (!mask[r][c]) continue;
			const t = ((r - rc) * 0.8 + (c - cc) * 0.55) / R;   // 左上→右下の明暗軸
			fdPut(g, r, c, t < -0.66 ? ramp.glow : t < -0.30 ? ramp.hi : t < 0.22 ? ramp.mid : ramp.sh);
		}
	}
	for (const [lr, lc, rad] of lobes.filter(L => L[3])) {
		for (let c = lc - rad; c <= lc + rad; c++) {
			const dr = Math.round(Math.sqrt(Math.max(0, rad * rad - (c - lc) ** 2)));
			const r = lr + dr;
			if (!mask[r]?.[c]) continue;
			if (!(mask[r + 1]?.[c])) continue;                  // 輪郭は fdRim に任せる
			fdPut(g, r, c, ramp.sh);
			if (mask[r - 1]?.[c] && g[r - 1][c] === ramp.sh) fdPut(g, r - 1, c, ramp.mid);
		}
	}
	fdRim(g, ramp.rimS, ramp.rimB);
	return fdSeal(g);
}

// ── 木（パレット: 1=最暗 2=暗 3=中 4=明 5=幹明 6=幹暗 7=葉の日向）─────────
// frame1 は「風で葉がざわつく」＝房の位置を少しずらす。絵全体を横にずらすと
// 木そのものが飛んで見える（試作で確認）∴動かすのは一部の房だけ。
//
// 10a-4：樹冠の房の並びを**変種ごとに**持つ（[コマ0の房, コマ1の房]）。幹は共通＝
// どの変種でも「幹が樹冠の下に 4 ドット以上見える」（field-tiles-32 ⑧）を保つ。
// ⚠ 房を動かすと影絵の幅・高さ・中心が動く＝18〜25 ドット／中心±1 の枠から出ると
//    「隣のセルへずれた木」「セルを埋める木」になる∴変種ごとに枠内に収める。
const TREE_SHAPES = [
	// 0＝丸く広い樹冠（従来の絵＝基本名 `tree` もこれ）
	[[[11, 15, 7], [11, 11, 6], [11, 20, 6], [16, 11, 4, 1], [16, 20, 4, 1]],
		[[11, 15, 7], [11, 12, 6], [11, 20, 6], [16, 12, 4, 1], [16, 21, 4, 1]]],
	// 1＝背が高く細い（幹が長く見える＝林の中の高木）
	[[[10, 15, 7], [13, 11, 5], [13, 20, 5], [17, 12, 4, 1], [17, 19, 4, 1]],
		[[10, 16, 7], [13, 11, 5], [13, 21, 5], [17, 12, 4, 1], [17, 20, 4, 1]]],
	// 2＝低く横に広い（枝を張った古木）
	[[[13, 15, 7], [13, 10, 6], [13, 21, 6], [17, 12, 4, 1], [17, 19, 4, 1]],
		[[13, 15, 7], [13, 11, 6], [13, 21, 6], [17, 13, 4, 1], [17, 20, 4, 1]]],
	// 3＝左右が非対称（片側の枝が伸びた木）＝中心は±1に収める
	[[[11, 16, 7], [12, 11, 5], [10, 20, 6], [16, 12, 4, 1], [16, 20, 4, 1]],
		[[11, 16, 7], [12, 12, 5], [10, 20, 6], [16, 13, 4, 1], [16, 21, 4, 1]]],
];
const TREE_RAMP = { glow: 7, hi: 4, mid: 3, sh: 2, rimS: 2, rimB: 1 };
function treeGrid(lobes) {
	const g = fdBlank();
	for (let r = 16; r <= 26; r++) {
		fdPut(g, r, 14, 6); fdPut(g, r, 15, 5); fdPut(g, r, 16, 5); fdPut(g, r, 17, 6);
	}
	fdSpan(g, 25, 13, 18, 6); fdSpan(g, 26, 12, 19, 6);      // 根張り
	fdPut(g, 25, 15, 5); fdPut(g, 25, 16, 5);
	// 樹冠は別の紙に描いて輪郭を付けてから幹の上に重ねる
	// （同じ紙でやると幹の縁まで葉の色で縁取ってしまう）
	const canopy = fdFoliage(lobes, TREE_RAMP);
	for (let r = 0; r < FIELD_ART_N; r++) {
		for (let c = 0; c < FIELD_ART_N; c++) if (canopy[r][c]) fdPut(g, r, c, canopy[r][c]);
	}
	return fdSeal(g);
}

// 風で揺れる絵（木・茂み）の変種を作り置きする（`SPRITES` は import 時の spread ∴
// 後から足せない）。変種 v ＝ **形 `v>>1` × 揺れの位相 `v&1`**。
//
// 🔴 位相をコマの順の入れ替えで作る理由＝コマを選ぶのは世界に1つの `animFrame`
//    （`shared/sprites.js` の `startAnimLoop`／`drawSprite` は `animFrame % frames.length`）。
//    ∴形を増やしただけでは「林全体が同じ瞬間に同じ向きへざわつく」が残る。
//    コマの順を入れ替えた絵を隣に置けば、同じ瞬間に逆のコマが出る＝ざわつきがばらける。
//    エンジン（makeSprite/drawSprite/redrawAnimSprites）は一切触らない＝位相を
//    「絵の名前」に織り込む＝読み手（ゲーム・エディタ）を増やさない。
//    ⚠ コマは2枚しか無い∴位相も2種類が上限（それ以上は絵を増やすしかない）。
function registerSwayVariants(base, framePairs) {
	const n = framePairs.length * 2;
	for (let v = 0; v < n; v++) {
		const [f0, f1] = framePairs[v >> 1];
		TILE_SPRITES[`${base}#${v}`] = (v & 1) ? [f1, f0] : [f0, f1];
	}
	OBJ_VARIANTS[base] = n;
	// 基本名＝形0・位相0（TILE_SPRITE_MAP・エディタのパレット見本が参照する代表1枚）
	TILE_SPRITES[base] = TILE_SPRITES[`${base}#0`];
}

registerSwayVariants('tree', TREE_SHAPES.map(([a, b]) => [treeGrid(a), treeGrid(b)]));

// ── 山（パレット: 1=最暗 2=影 3=中 4=明 5=雪/熾火 6=輪郭）───────────────
// 行ごとの左右の張り出しを手で決める（左右対称の等差だと定規で引いた三角に見える）。
//
// 10a-1d：同じ `'M'` タイルを**下地から選んだ肌**で描き分ける（`shared/tile-skins.js`）。
// 5種＝雪冠つきの高山（草地）／黒い火山（火山灰）／雪山（雪原）／砂岩のメサ（砂）／
//       低い岩山（泥）。輪郭表・雪線・模様・パレットを肌ごとに持つ。
