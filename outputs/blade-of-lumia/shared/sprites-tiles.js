// 「屋根が張り出している」ように読める。
TILE_SPRITES.houseRoofEaveS = [hsGrid((r, c) => {
	if (r < HS_N - 5) return 0;
	if (r === HS_N - 5) return c % 8 === 0 ? 2 : 4;        // 瓦の先端
	if (r === HS_N - 4) return 1;                          // 小口の影
	if (r <= HS_N - 2) return 6;                           // 軒下の木部
	return 1;
})];
