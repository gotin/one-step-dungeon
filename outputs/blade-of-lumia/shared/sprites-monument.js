// ── Blade of Lumia – 石碑（MONUMENT・`†`）と転移の石碑（WARP_STONE・`‡`）の絵 ── キュー27 ──
//
// 何を描くか：旧＝「〜の石碑」も「道標」も同じ木の看板 `i` の絵だった（2026-09-20 ユーザー指摘
// 「そもそも、『石碑』じゃないよね？看板じゃんただの。」）。参考画像＝`refs/石碑.png`
// （角を落とした縦長の碑・2段の台座・苔・刻まれた紋様・肩のひび）。
//
// ✅ 叩き台（2026-10-03・`.scratch/q27-gen.js`）をユーザーが「この方向で OK」と判定した絵。
//    色は石畳・壁の青灰色に埋もれないよう黄みの暖かい灰色（最初の青灰色の版は石畳の上で
//    見えなかった）。看板（板 18 幅＋柱）より背が高く太い＝見分けが付く。
//
// 転移の石碑は**同じ碑の刻みの色だけ**を変える（ユーザー判定「ワープできる石碑は見た目も
// 少し変えるとよさそう」）：
//   warpStone    … まだ触れていない＝紋が暗い青
//   warpStoneLit … 灯った＝紋が明るい水色＋紋の周りに淡い光
// ∴刻みを専用の番号（6＝彫り込み／9＝彫り込みの下の光）で描き、色はパレットで切り替える。
//
// パレットの番号：1 輪郭 / 2 石・陰 / 3 石・中 / 4 石・明 / 5 石・光 / 6 刻み /
//                 7 苔・暗 / 8 苔・明 / 9 刻みの下の光 / 10 紋の周りの光（灯った碑だけ）
const N = 32;
const hash = (x, y, s) => {
	let h = (x * 374761393 + y * 668265263 + s * 2147483647) | 0;
	h = (h ^ (h >>> 13)) * 1274126177 | 0;
	return ((h ^ (h >>> 16)) >>> 0) / 4294967296;
};

function monumentGrid() {
	const g = Array.from({ length: N }, () => new Array(N).fill(0));
	const put = (y, x, v) => { if (y >= 0 && y < N && x >= 0 && x < N) g[y][x] = v; };
	// 碑の本体：角を落とした頭（y=2..5）＋縦の胴（y=6..24）
	const span = (y) => y === 2 ? [13, 18] : y === 3 ? [11, 20] : y === 4 ? [10, 21] : [9, 22];
	for (let y = 2; y <= 24; y++) {
		const [a, b] = span(y);
		for (let x = a; x <= b; x++) {
			let v = 3;
			if (x <= a + 2) v = 4;                 // 左の面に光
			if (x >= b - 2) v = 2;                 // 右の面は陰
			if (y <= 4) v = x >= b - 1 ? 3 : 5;    // 頭の面に光
			if (v === 3 && hash(x, y, 3) < 0.06) v = 4;
			if (v === 3 && hash(x, y, 5) < 0.05) v = 2;
			if (v === 4 && hash(x, y, 7) < 0.06) v = 3;
			put(y, x, v);
		}
		put(y, a, 1); put(y, b, 1);
	}
	for (let x = 13; x <= 18; x++) put(1, x, 1);   // 頭の輪郭
	put(2, 11, 1); put(2, 12, 1); put(3, 10, 1); put(4, 9, 1); put(2, 19, 1); put(2, 20, 1); put(3, 21, 1); put(4, 22, 1);
	// 刻み：上に紋（輪を縦棒が上下に貫く）・下に古い文字（2画ずつの短い刻み＝縞に見せない）
	const glyph = (pts) => { for (const [y, x] of pts) { put(y, x, 6); if (g[y + 1]?.[x] !== 6) put(y + 1, x, 9); } };
	glyph([[6, 15], [6, 16], [7, 14], [7, 17], [8, 13], [8, 18], [9, 13], [9, 18], [10, 14], [10, 17], [11, 15], [11, 16],
		[5, 15], [5, 16], [12, 15], [12, 16], [13, 15], [13, 16], [8, 15], [8, 16], [9, 15], [9, 16]]);
	glyph([[16, 12], [16, 13], [17, 13], [16, 16], [17, 16], [16, 17], [16, 19], [17, 19]]);
	glyph([[19, 12], [20, 12], [20, 13], [19, 15], [19, 16], [20, 16], [19, 18], [20, 19]]);
	glyph([[22, 13], [22, 14], [22, 17], [23, 17], [22, 18]]);
	// ひび：右の肩から斜めに
	for (const [y, x] of [[3, 19], [4, 19], [5, 20], [6, 20], [7, 19], [8, 19], [9, 20], [10, 20], [11, 21]]) put(y, x, 1);
	// 台座：碑より広い2段
	for (let y = 24; y <= 30; y++) {
		const [a, b] = y <= 26 ? [7, 24] : [5, 26];
		for (let x = a; x <= b; x++) {
			let v = y === 25 || y === 28 ? 5 : y >= 29 ? 2 : 3;
			if (x >= b - 2 && v > 2) v--;
			put(y, x, v);
		}
		put(y, a, 1); put(y, b, 1);
	}
	for (let x = 7; x <= 24; x++) if (x <= 9 || x >= 22) put(24, x, 1);
	for (let x = 5; x <= 7; x++) put(27, x, 1);
	for (let x = 24; x <= 26; x++) put(27, x, 1);
	for (let x = 5; x <= 26; x++) put(31, x, 1);   // 地際
	put(28, 15, 1); put(29, 16, 1); put(30, 16, 1); // 台座の継ぎ目
	// 苔：胴の左下・台座の両端
	for (const [y, x, v] of [[19, 10, 7], [20, 10, 8], [21, 10, 8], [21, 11, 7], [22, 10, 7], [23, 11, 8], [23, 10, 8],
		[25, 8, 8], [25, 9, 7], [26, 8, 7], [29, 6, 8], [30, 6, 7], [30, 7, 8], [29, 7, 7], [28, 6, 8],
		[25, 22, 8], [26, 23, 7], [30, 24, 8], [30, 25, 7], [29, 25, 8], [22, 21, 8], [23, 21, 7], [24, 20, 8]]) put(y, x, v);
	return g;
}

// 灯った転移碑＝紋の周りの石の面に淡い光（10）を置く（輪郭・刻みは上書きしない）
function litGrid() {
	const g = monumentGrid().map((row) => row.slice());
	for (const [y, x] of [[4, 14], [4, 17], [5, 14], [5, 17], [6, 13], [6, 18], [7, 12], [7, 19], [8, 12], [9, 12],
		[10, 12], [10, 19], [11, 13], [11, 18], [12, 14], [12, 17], [13, 14], [13, 17], [14, 15], [14, 16]]) {
		if (g[y][x] && g[y][x] !== 1 && g[y][x] !== 6 && g[y][x] !== 9) g[y][x] = 10;
	}
	return g;
}

export const MONUMENT_SPRITES = {
	monument:     [monumentGrid()],
	warpStone:    [monumentGrid()],
	warpStoneLit: [litGrid()],
};

