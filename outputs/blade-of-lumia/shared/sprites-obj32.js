	line(g, 6, 10, 13, 15, 4, 1);
	line(g, 6, 21, 13, 16, 4, 1);
	line(g, 6, 10, 13, 15, 5, 1);
	// 胸の陰
	disc(g, 11, 11, 2, 2);
	disc(g, 11, 20, 2, 2);
	// 中央の宝珠
	disc(g, 13, 15, 2, 4);
	disc(g, 13, 15, 1, 6);
	put(g, 12, 15, 3);
	// 腰帯（金・中央にも宝珠）
	rect(g, 22, 8, 24, 23, 4);
	rect(g, 22, 9, 23, 22, 5);
