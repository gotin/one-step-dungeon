// ハートのかけら（実行キュー13）＝ハートの左上の4分の1。4つ集めると器1個。
// 同じ輪郭（heartMask）から切り出す＝HUD の器と並べても房の丸みが揃う。
// 切り口は1ドットずつ互い違いにして「割れた欠片」に見せる（まっすぐ切ると
