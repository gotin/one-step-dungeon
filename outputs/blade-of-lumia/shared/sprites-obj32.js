// かけらの集まり具合（ポーズ画面の表示・1〜3個）＝器の輪郭を4つに割り、
// 集めた分だけ赤・残りは灰。並びは左上→右上→右下→左下（時計回り）。
// heartHalf パレット：1黒 3赤 4明赤 6中灰（半ハートと同じ色の組）。
function heartQuarterGrid(n) {
	const mask = heartMask();
	const g = blank();
	for (let r = 0; r < N; r++) for (let c = 0; c < N; c++) {
		if (!mask[r][c]) continue;
		const top = r <= 15, left = c <= 16;
		const q = top ? (left ? 0 : 1) : (left ? 3 : 2);
		put(g, r, c, q < n ? 3 : 6);
	}
	disc(g, 11, 12, 1, 4);
	strokeOutside(g);
	return g;
}

// ── UI アイコン（10e）── 絵文字を自前スプライトに置き換えるために新規に描いた4種 ──
// これまで絵が無かった物（🪽 翼の羽衣／🎵 笛／🕯 ロウソク／🎲 ガチャ）。
// ⚠️ 盤面タイルは持たない＝HUD・ポーズ・ショップの小さい canvas だけで使う∴他の
//    OBJ32 と違い「セル全面に貼る前提の余白」は要らない（見かけの大きさは呼び出し側が
//    ink から正規化する）。
//
// 縁の付け方＝strokeOutside（外へ1ドット足す）ではなく **一番外の不透明ドットを暗くする**。
// 理由＝この4種は 26 ドット前後まで使い切っており、外へ広げる余地が無い。
// ⚠️ 幅3ドット以下の部分は縁で塗り潰れる∴細い部分（羽軸・笛の指孔・目）は縁の**後**に描く。
const darkenRim = (g, v = 1) => {
	const src = g.map(row => row.slice());
	for (let r = 0; r < N; r++) {
		for (let c = 0; c < N; c++) {
			if (src[r][c] === 0) continue;
			const open = (src[r - 1]?.[c] ?? 0) === 0 || (src[r + 1]?.[c] ?? 0) === 0
				|| (src[r][c - 1] ?? 0) === 0 || (src[r][c + 1] ?? 0) === 0;
			if (open) g[r][c] = v;
		}
	}
};

// 翼の羽衣（飛行ボタン・古代の祭壇の報酬）── ink 17×26。
// wingRobe パレット：1輪郭 2羽軸/陰 3羽枝の陰 4白 5金の飾り紐。
// ⚠️ 経緯＝①OpenAI 生成は黒縁＋蝙蝠に見えて不採用 ②左右2枚の翼は1枚 12 ドット幅で
//    「蝶ネクタイ」 ③厚い片翼は「ナイフ」 → ④1枚の羽根で確定（`.scratch/draw-10e-icons.mjs`）。
//    羽枝を「軸に直交する 45°方向」へ伸ばすと y+x が一定＝同じパリティのセルだけ塗られて
//    市松になる∴**行ごとに中心と半幅**で定義する。
function wingRobeGrid() {
	const g = blank();
	const Y0 = 3, Y1 = 28;
	const cx = (y) => 12 + Math.round((y - Y0) * 0.34);   // 少し右へ倒れた羽軸
	const half = (y) => {
		let h;
		if (y <= Y0 + 5) h = y - Y0;              // 先端
		else if (y <= 20) h = 6;                  // 一番広い所
		else if (y <= 24) h = 6 - (y - 20);       // 根元へ絞る
		else h = 1;                               // 柄（軸だけ）
		return Math.max(h - (y % 3 === 0 ? 1 : 0), 0);   // 3行おきに1段浅く＝羽枝の刻み
	};
	for (let y = Y0; y <= Y1; y++) {
		const c = cx(y), h = half(y);
		for (let x = c - h; x <= c + h; x++) put(g, y, x, 4);
		if (h >= 2) { put(g, y, c + h, 3); put(g, y, c + h - 1, 3); }   // 右側は陰
	}
	darkenRim(g);
	for (let y = Y0 + 2; y <= 24; y++) put(g, y, cx(y), 2);            // 羽軸（縁の後）
	for (let y = 25; y <= Y1; y++) { put(g, y, cx(y), 1); put(g, y, cx(y) + 1, 2); }
	// 金の飾り紐＝行ごとに軸へ合わせる（22-23 行をまとめて矩形にすると軸から1ドットずれる）
	rect(g, 22, cx(22) - 1, 22, cx(22) + 1, 5);
	rect(g, 23, cx(23) - 1, 23, cx(23) + 1, 5);
	return g;
}

// 笛（ITEM_META.flute）── ink 29×27。パンフルート（縦管5本）。
// flute パレット：1輪郭/管口/紐 2陰 3中 4明 5ハイライト。
// ⚠️ 経緯＝①生成物は太すぎて「ソーセージ」 ②横笛は太さ5＋縁2ドットで内側が1〜2行しか
//    残らず指孔も金のリングも潰れて「棒パン」 → ③縦管の反復にして確定。
//    上端を階段・下端を揃えると「棒グラフ」に見える∴実物どおり**上端を揃えて下端を段違い**。
//    束ねる紐は縁の**後**に管の隙間まで塗る（前に引くと隙間で切れて3つの塊に割れる）。
function panFluteGrid() {
	const g = blank();
	const COUNT = 5, W = 5, X0 = 2, TOP = 3;
	const shade = [3, 5, 4, 3, 2];        // 管の左から＝丸みを出す
	for (let i = 0; i < COUNT; i++) {
		const x0 = X0 + i * (W + 1), bot = 29 - i * 2;   // 段差3だと右端の管が紐の直下で切れる
		for (let x = x0; x < x0 + W; x++) for (let y = TOP; y <= bot; y++) put(g, y, x, shade[x - x0]);
		rect(g, TOP, x0, TOP, x0 + W - 1, 1);            // 管口（暗い穴）
		rect(g, TOP + 1, x0 + 1, TOP + 1, x0 + W - 2, 1);
	}
	darkenRim(g);
	const XE = X0 + COUNT * (W + 1) - 2;
	for (const y of [8, 14]) { rect(g, y, X0, y, XE, 1); rect(g, y + 1, X0, y + 1, XE, 2); }
	return g;
}

