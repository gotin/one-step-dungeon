// 鍵（floor drop のみ）── ink 11×14・2コマ（frame1=輝き）。輪（ドーナツ）＋軸＋歯。
// key パレット：1輪郭 2暗金 3中金 4明金 5白（輝き用）。
// ❌ 失効（2026-09-08・ユーザー指摘＝「鍵ももうちょっと鍵らしい絵に改善できる気が
// する。今はドアだけがやけにリアル」）＝旧版は輪・軸・歯のすべてが単色の面塗りで、
// 扉（10d-2・多段の陰影）と並ぶと情報量の差が目立った。✅ やり直し＝光源を他の絵と
// 同じ左上に統一し、輪は象限で塗り分け・軸は左右の縁1ドットだけ明暗・歯は3層（明→中→暗）
// で厚みを付けた（重ねた円で中心をずらす手法は輪の形そのものが歪むため、角度判定で
// 1つの円から作る）。
function keyGrid(bright) {
	const g = blank();
	const dark = 2, mid = bright ? 4 : 3, hi = bright ? 5 : 4;
	const cr = 13, cc = 15, rOuter = 4, rInner = 2;
	for (let r = cr - rOuter; r <= cr + rOuter; r++) {
		for (let c = cc - rOuter; c <= cc + rOuter; c++) {
			const d2 = (r - cr) ** 2 + (c - cc) ** 2;
			if (d2 > rOuter * rOuter + rOuter * 0.4) continue;
			if (d2 < rInner * rInner + rInner * 0.4) continue; // 中空
			const dr = r - cr, dc = c - cc;
			let v = mid;
			if (dr <= 0 && dc <= 0) v = hi;         // 左上＝明
			else if (dr >= 1 && dc >= 1) v = dark;  // 右下＝暗
			put(g, r, c, v);
		}
	}
	// 軸＝中間色で塗り、左右の縁1ドットだけ明暗にして丸みを出す
	rect(g, 15, 15, 21, 16, mid);
	for (let r = 15; r <= 21; r++) { put(g, r, 15, hi); put(g, r, 16, dark); }
	// 歯＝長さの違う2枚。上面は明・本体は中間・下面は暗の3層で厚みを出す
	rect(g, 17, 17, 17, 19, hi);
	rect(g, 18, 17, 18, 19, mid);
	rect(g, 19, 17, 19, 19, dark);
	rect(g, 21, 17, 21, 18, hi);
	rect(g, 22, 17, 22, 18, dark);
	strokeOutside(g);
	// 中空を輪郭でも塞がせない
	for (let r = cr - rInner; r <= cr + rInner; r++) {
		for (let c = cc - rInner; c <= cc + rInner; c++) {
			const d2 = (r - cr) ** 2 + (c - cc) ** 2;
			if (d2 < rInner * rInner + rInner * 0.4) put(g, r, c, 0);
		}
	}
	return g;
}

// ルピー（floor drop・ブーメラン運搬アイコンと共用）── ink 15×15。六角の宝石。
// rupee パレット：1輪郭 2暗緑 3中緑 4明緑 5白（煌めき用）。
// ❌ 失効（2026-09-08・(c) ユーザー判定 NG）＝旧版は上下の頂点で半幅が
// 0→2 ドットへ一気に跳ぶ（1行で急に広がる）ため「上下が不自然に尖る」と
// 指摘された。✅ やり直し＝半幅テーブルを1行ごとに必ず1ドットだけ変える
// （2ドット以上の跳びを禁止）＝頂点までなめらかに絞る。
function rupeeGrid() {
	const g = blank();
	const HALF_TABLE = [0, 1, 2, 3, 4, 5, 6, 6, 6, 6, 5, 4, 3, 2, 1, 0]; // rows10..25
	const halfAt = (r) => (r < 10 || r > 25) ? -1 : HALF_TABLE[r - 10];
	for (let r = 10; r <= 25; r++) {
		const h = halfAt(r);
		if (h < 0) continue;
		rect(g, r, 16 - h, r, 16 + h, 3);
	}
	for (let r = 11; r <= 24; r++) {
		put(g, r, 16 - Math.max(1, halfAt(r) - 1), 4);
		put(g, r, 16 + Math.max(1, halfAt(r) - 1), 2);
	}
	put(g, 13, 15, 5); put(g, 13, 16, 5);
	strokeOutside(g);
	return g;
}

// 星の欠片（floor drop のみ）── ink 17×21。青い結晶（菱形）。
// ❌ 旧デザイン（金の三角形）は 2026-09-09 ユーザー指摘「かけらに見えない
// …下辺が長い三角形になってて」で失効＝形も色も描き直した（10g）。
// 形はユーザー提示の参考画像（.scratch/ref-star-piece.png・実測 14×16 ドット＝
// `.scratch/detect-dot-grid.mjs` で実測）から比率を写した＝上下に尖る菱形で
// 中心へ向かって明るくなる同心の帯＋縦に貫く光の筋（結晶のハイライト）。
// ⚠️ 他の落ちアイテム（sword 20×19／bow 18×19 等）と背丈を揃える＝参考画像の
// 比率のまま素直に大きく描くと高さ25まで伸びて1体だけ突出する（`.scratch/proto-10g.mjs`
// で試作・実測して縮めた）。
// triforce パレット：1輪郭 2外周（暗青） 3中間（青） 4水色 5芯（白）。
function triforceGrid() {
	const g = blank();
	const cr = 16, cc = 16;
	// 中心が最も広い菱形を外側から内側へ重ねる（同心の帯で濃淡を作る）
	const diamond = (R, half0, v) => {
		for (let dr = -R; dr <= R; dr++) {
			const half = Math.round(half0 * (R - Math.abs(dr)) / R);
			if (half < 0) continue;
			rect(g, cr + dr, cc - half, cr + dr, cc + half, v);
		}
	};
	diamond(9, 7, 2);
	diamond(7, 5, 3);
	diamond(4, 3, 4);
	diamond(2, 1, 5);
	// 中央を貫く光の筋
	for (let r = cr - 7; r <= cr + 7; r++) put(g, r, cc, 5);
	strokeOutside(g);
	return g;
}

