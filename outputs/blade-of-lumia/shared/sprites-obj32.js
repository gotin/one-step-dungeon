// 盾（floor drop・装備中の正面オーバーレイと共用）── ink 15×19。西洋盾（ハート型）
// の輪郭＋中央の金の紋章。shield パレット：1輪郭 2暗青 3中青 4金(紋章) 5白。
// ❌ 失効（2026-09-08・(c) ユーザー判定 NG）＝旧版は rrect の丸みで輪郭が
// 「盾」に見えず「ギターの胴／ひょうたん」に見えた。ユーザーの言葉＝「全然盾に
// 見えないんだけど…バイオリンのボディ部分？左側にある黄色い線はなに？ひょうたん？」。
// 原因は2つ＝(1) 上部を rrect(cut=3) の強い丸みで描いたため直線的な「盾」の
// 輪郭にならず有機的な丸い塊に見えた (2) 左右の陰影に紋章専用色(4=金/オリーブ)を
// 使ったため、体の縁全体が金色の帯になり「弦楽器の縁」に見えた。
// ✅ やり直し＝上部は直線の矩形（角を1ドットだけ落とす）・下部は直線で1点へ絞る
// 三角＝西洋の盾（ヒーターシールド）の輪郭を明確にした。陰影は体専用の色(2/3)
// だけを使い、紋章専用色(4/5)は中央の十字だけに限定（[[blade-fixed-box-sprite-scale]]
// と同じ「色の役割を絵の全域に流用しない」教訓）。
function shieldGrid() {
	const g = blank();
	const c0 = 9, c1 = 23, mid = 16; // 上部の全幅（cols9..23・重心=16）
	rect(g, 9, c0, 17, c1, 3);                // 上部（矩形）
	put(g, 9, c0, 0); put(g, 9, c1, 0);       // 角を1ドット落として直角を殺す
	for (let i = 0; i <= 7; i++) rect(g, 18 + i, c0 + i, 18 + i, c1 - i, 3); // 下部（直線で1点へ）
	// 右半分を暗く（縦の合わせ目・立体感）＝体専用色(2)だけを使う
	for (let r = 9; r <= 17; r++) rect(g, r, mid + 1, r, c1, 2);
	for (let i = 0; i <= 7; i++) { const cc1 = c1 - i; if (mid + 1 <= cc1) rect(g, 18 + i, mid + 1, 18 + i, cc1, 2); }
	// 紋章（金の十字・中央）＝この小さい範囲だけで色4/5を使う
	rect(g, 12, mid - 1, 20, mid + 1, 5);
	rect(g, 15, mid - 4, 15, mid + 4, 5);
	rect(g, 13, mid, 19, mid, 4);
	strokeOutside(g);
	return g;
}

// 盾・側面（10d-5・両凸→片凸に描き直し）── ink 12×21。
// ❌ 失効（2026-09-09・ユーザー指摘＝「どら焼きみたいに両面が膨らんでいる」）＝
// 旧版は中心軸(mid)から左右対称に膨らむ菱形＝盾の厚み方向の断面が両凸レンズに
// 見えた（盾は片面だけ凸のはず）。✅ やり直し＝表面側(mid+側)だけ半径7まで丸く
// 張り出す・背面側(mid-側)は半径2止まりの浅い平面＝平凸レンズ形にした。
// shield パレット共用：1輪郭 2暗青 3中青 5白（4金は側面に写らない）。
function shieldSideGrid() {
	const g = blank();
	const HALF_R = [0, 1, 2, 3, 4, 5, 6, 7, 7, 7, 7, 7, 6, 5, 4, 3, 2, 1, 0]; // 表面側(凸)・19行
	const HALF_L = [0, 1, 1, 2, 2, 2, 2, 2, 2, 2, 2, 2, 2, 2, 2, 2, 1, 1, 0]; // 背面側(平ら・浅い)
	const r0 = 6, mid = 16;
	for (let i = 0; i < HALF_R.length; i++) {
		const r = r0 + i, hr = HALF_R[i], hl = HALF_L[i];
		if (hr <= 0 && hl <= 0) { put(g, r, mid, 3); continue; }
		rect(g, r, mid - hl, r, mid + hr, 3);
	}
	// 表面(凸)の縁を一段暗く（丸みの立体感・半径が大きい区間だけ）
	for (let i = 0; i < HALF_R.length; i++) {
		const r = r0 + i, hr = HALF_R[i];
		if (hr >= 5) put(g, r, mid + hr, 2);
	}
	// 頂点にハイライト（凸の一番出っ張った3行だけ・縁の1つ内側＝縁取りにしない）
	for (let i = 8; i <= 10; i++) put(g, r0 + i, mid + HALF_R[i] - 1, 5);
	strokeOutside(g);
	return g;
}

