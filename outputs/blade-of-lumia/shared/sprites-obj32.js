// 弓（floor drop・HUD/ポーズの装備アイコン共用）── ink 15×28。
// ❌ 失効（2026-09-10・10h）＝旧デザインは矢を番えた形で、矢の軸が弓の弧を
// 直角に貫くため「ボーガン（クロスボウ）に見える」とユーザー指摘（参考画像
// 提示つき）。矢は飛翔中の絵（`arrow`・10d-4）と役割が重複しており、ここで
// 矢を持たせる必要はない。
// ✅ 描き直し＝ユーザー提示の参考画像（.scratch/ref-bow.png・実測 30×112
// ドット＝`.scratch/detect-dot-grid.mjs` で実測）の意匠（弦のみ・矢なし・
// リカーブボウの反り＋グリップの巻き革）を縦持ちのまま32ドットへ写した
// （ネイティブ比率をそのまま32へ写すと32×119になり他の落ちアイテムより
// 縦に突出する＝10gの星の欠片と同じ理由で高さを28へ抑えた）。
// bow パレット：1輪郭 2内側(暗) 3地 4外側(明) 5グリップ(革) 6先端(骨) 7弦。
function bowGrid() {
	const g = blank();
	const r0 = 3, r1 = 28;
	const STEPS = r1 - r0; // 25
	const cc = 15; // 弓本体の中心列（弦から見て右へ張り出す）
	const colAt = (i) => {
		const t = i / STEPS;
		let bulge = 6.5 * Math.sin(Math.PI * t);
		const tip = 2.0;
		if (t < 0.09) bulge -= tip * (1 - t / 0.09);
		if (t > 0.91) bulge -= tip * ((t - 0.91) / 0.09);
		return cc + bulge;
	};
	for (let i = 0; i <= STEPS; i++) {
		const t = i / STEPS;
		const r = r0 + i;
		const c = Math.round(colAt(i));
		const isGrip = t > 0.42 && t < 0.60;
		const isTip = t < 0.045 || t > 0.955;
		put(g, r, c - 1, isGrip ? 5 : (isTip ? 6 : 4));  // 外側（弦から遠い側）
		put(g, r, c,     isGrip ? 5 : (isTip ? 6 : 3));  // 中央
		put(g, r, c + 1, isGrip ? 5 : (isTip ? 6 : 2));  // 内側（弦寄り）
	}
	// 弦（両先端をまっすぐ結ぶ・本体より内側＝小さい列）
	const strC0 = Math.round(colAt(0)) - 3;
	const strC1 = Math.round(colAt(STEPS)) - 3;
	line(g, r0, strC0, r1, strC1, 7, 1);
	strokeOutside(g);
	return g;
}

