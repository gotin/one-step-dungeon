// 「聖なる鎧」から描き直し）── ink 28×28。armorLegend パレット：
// 1輪郭 2影（青灰） 3地・白銀 4金（暗） 5金（明） 6宝珠（青）。
// 実測（.scratch/detect-dot-grid.mjs）＝62×56 ドット相当（ピッチ ≒19.5px）。
// 写した特徴＝金縁の球体の肩当て（十字の紋章）／濃紺に沈む首元の開口＋金縁／
// 白銀の胸当てを縦に貫く金の背骨ライン＋斜めの鎖骨飾り／中央の青い宝珠／
// 金の腰帯（中央にも宝珠）／白銀の腰当て。青銅の鎧と骨格（肩当て・胸当て・
// 腰帯・腰当ての配置）を共有しつつ、色と装飾（金の縁取り・宝珠）だけで
// 別素材に見せる＝ユーザー確定「形は同じでも色替えでは布に見えない」の逆
// （ここは同系の金属鎧どうし∴骨格の共有は意匠の手抜きにならない）。
