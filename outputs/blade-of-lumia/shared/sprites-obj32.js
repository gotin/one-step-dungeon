// ハート型の輪郭マスク（heart／heartEmpty／heartHalf の3種で共有）── ink 17×16。
// HUD の HP バーは3種を並べて表示する＝形と ink 箱を完全一致させないと大きさが
// バーの中でガタつく（[[blade-tile-sprite-single-source]] と同じ「一覧を持たず
// 共通関数から導く」考え方をここでも適用）。
// ❌ 失効（2026-09-08・(c) ユーザー判定 NG）＝旧版は房の直下（row13）で
// 半幅が一気に7へ広がり、房の外径（半径3）よりも張り出す「翼」ができて
// 「左右が不自然に尖る」と指摘された。✅ やり直し＝半幅を房の外径と地続き
// （6）から始め、1行ごとに最大1ドットだけ狭める。
function heartMask() {
	const m = blank();
	disc(m, 12, 13, 3, 1);
	disc(m, 12, 19, 3, 1);
	const HALF_TABLE = [6, 6, 5, 5, 4, 3, 2, 1, 0]; // rows13..21
	for (let r = 13; r <= 21; r++) {
		const half = HALF_TABLE[r - 13];
		if (half <= 0) { put(m, r, 16, 1); continue; }
		rect(m, r, 16 - half, r, 16 + half, 1);
	}
	return m;
}
