// 90°/180° 回転はピクセル単位の入れ替えだけ＝劣化しない（CSS rotate は使わない）。
// 左向きは makeSprite の flipX で右向きを反転して作る。
function rot180(g) {
	return g.slice().reverse().map(row => row.slice().reverse());
}
function rot90cw(g) {
	const h = g.length, w = g[0].length;
	return Array.from({ length: w }, (_, r) =>
		Array.from({ length: h }, (_, c) => g[h - 1 - c][r]));
}

